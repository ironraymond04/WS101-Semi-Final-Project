create function admin_dispose_found_notice(notice_id uuid, outcome text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;
  if char_length(trim(outcome)) not between 1 and 1000 then raise exception 'Disposition outcome is required'; end if;
  perform 1 from found_notices where id = notice_id and status = 'received' for update;
  if not found then raise exception 'Found item is not available for disposition'; end if;
  if exists (
    select 1 from claim_attempts
    where found_notice_id = notice_id and status in ('pending', 'needs_info', 'approved')
  ) then raise exception 'Resolve active claims before disposition'; end if;
  update found_notices
  set status = 'disposed', disposed_at = now(), disposition = trim(outcome), updated_at = now()
  where id = notice_id and status = 'received';
  if not found then raise exception 'Found item is not available for disposition'; end if;
  insert into item_audit_log(action, found_notice_id, details)
  values ('found_item_disposed', notice_id, jsonb_build_object('outcome', trim(outcome)));
end;
$$;

create function admin_appoint_admin(user_id uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;
  if user_id = auth.uid() then raise exception 'Admins cannot change their own role'; end if;
  update profiles set role = 'admin'
  where id = user_id and role = 'student'
    and exists (
      select 1 from auth.users u join campus_email_domains d
        on lower(split_part(u.email, '@', 2)) = d.domain
      where u.id = profiles.id and u.email_confirmed_at is not null
    );
  if not found then raise exception 'Student profile not found'; end if;
  insert into item_audit_log(action, details)
  values ('admin_appointed', jsonb_build_object('user_id', user_id));
end;
$$;

