create table lost_reports (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 3 and 100),
  description text not null check (char_length(description) between 10 and 1000),
  category_id integer not null references categories(id),
  last_seen_on date,
  last_seen_location text check (last_seen_location is null or char_length(last_seen_location) <= 120),
  image_path text,
  status lost_report_status not null default 'open',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table found_notices (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 3 and 100),
  description text not null check (char_length(description) between 10 and 1000),
  category_id integer not null references categories(id),
  found_at_on date,
  found_at_location text check (found_at_location is null or char_length(found_at_location) <= 120),
  image_path text,
  status found_notice_status not null default 'pre_desk',
  canonical_found_notice_id uuid references found_notices(id),
  received_at timestamptz,
  disposed_at timestamptz,
  disposition text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'duplicate' and canonical_found_notice_id is not null)
    or (status <> 'duplicate' and canonical_found_notice_id is null)
  ),
  check (
    (status in ('received', 'reserved', 'returned', 'disposed') and received_at is not null)
    or status not in ('received', 'reserved', 'returned', 'disposed')
  ),
  check (
    (status = 'disposed' and disposed_at is not null and disposition is not null)
    or status <> 'disposed'
  )
);

create table report_owners (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references profiles(id) on delete cascade,
  lost_report_id uuid unique references lost_reports(id) on delete cascade,
  found_notice_id uuid unique references found_notices(id) on delete cascade,
  created_at timestamptz not null default now(),
  check ((lost_report_id is null) <> (found_notice_id is null))
);

create table lost_report_private_details (
  lost_report_id uuid primary key references lost_reports(id) on delete cascade,
  details text not null default '' check (char_length(details) <= 1000)
);

create table found_notice_private_details (
  found_notice_id uuid primary key references found_notices(id) on delete cascade,
  details text not null default '' check (char_length(details) <= 1000)
);

create table possible_matches (
  found_notice_id uuid not null references found_notices(id) on delete cascade,
  lost_report_id uuid not null references lost_reports(id) on delete cascade,
  created_by uuid not null default auth.uid() references profiles(id),
  created_at timestamptz not null default now(),
  primary key (found_notice_id, lost_report_id)
);

create table claim_attempts (
  id uuid primary key default gen_random_uuid(),
  found_notice_id uuid not null references found_notices(id),
  claimant_id uuid not null references profiles(id),
  lost_report_id uuid references lost_reports(id),
  evidence text not null check (char_length(evidence) between 10 and 2000),
  status claim_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index one_active_claim_attempt_per_student
  on claim_attempts(found_notice_id, claimant_id)
  where status in ('pending', 'needs_info', 'approved');
create unique index one_active_reservation_per_found_notice
  on claim_attempts(found_notice_id)
  where status = 'approved';
create index claim_attempts_review_queue on claim_attempts(status, created_at);

create table claim_messages (
  id uuid primary key default gen_random_uuid(),
  claim_id uuid not null references claim_attempts(id) on delete cascade,
  sender_id uuid not null default auth.uid() references profiles(id),
  message text not null check (char_length(message) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table item_audit_log (
  id bigint generated always as identity primary key,
  actor_id uuid not null default auth.uid() references profiles(id),
  action text not null,
  lost_report_id uuid references lost_reports(id),
  found_notice_id uuid references found_notices(id),
  claim_id uuid references claim_attempts(id),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index lost_reports_search on lost_reports(status, created_at desc);
create index found_notices_search on found_notices(status, created_at desc);
create index possible_matches_by_lost_report on possible_matches(lost_report_id);

create function current_user_is_admin() returns boolean
language sql security definer stable set search_path = public, auth as $$
  select exists (
    select 1
    from profiles p
    join auth.users u on u.id = p.id
    join campus_email_domains d on lower(split_part(u.email, '@', 2)) = d.domain
    where p.id = auth.uid() and p.role = 'admin' and u.email_confirmed_at is not null
  );
$$;

create function current_user_is_campus_member() returns boolean
language sql security definer stable set search_path = public, auth as $$
  select exists (
    select 1
    from profiles p
    join auth.users u on u.id = p.id
    join campus_email_domains d on lower(split_part(u.email, '@', 2)) = d.domain
    where p.id = auth.uid() and u.email_confirmed_at is not null
  );
$$;

create function owns_lost_report(report_id uuid) returns boolean
language sql security definer stable set search_path = public as $$
  select exists (
    select 1 from report_owners o
    where o.lost_report_id = report_id and o.owner_id = auth.uid()
  );
$$;

create function owns_found_notice(notice_id uuid) returns boolean
language sql security definer stable set search_path = public as $$
  select exists (
    select 1 from report_owners o
    where o.found_notice_id = notice_id and o.owner_id = auth.uid()
  );
$$;

create function create_lost_report(
  report_id uuid,
  report_title text,
  report_description text,
  report_category_id integer,
  seen_on date,
  seen_location text,
  private_details text,
  report_image_path text
) returns uuid
language plpgsql security definer set search_path = public as $$
begin
  if not current_user_is_campus_member() then raise exception 'Verified campus account required'; end if;
  if not exists (select 1 from categories where id = report_category_id and active) then
    raise exception 'Choose an active category';
  end if;
  if report_image_path is not null and report_image_path !~ (
    '^users/' || auth.uid()::text || '/[0-9a-f-]{36}\.(jpg|png|webp)$'
  ) then raise exception 'Invalid report image path'; end if;
  insert into lost_reports(id, title, description, category_id, last_seen_on, last_seen_location, image_path)
  values (report_id, report_title, report_description, report_category_id, seen_on, seen_location, report_image_path);
  insert into report_owners(owner_id, lost_report_id) values (auth.uid(), report_id);
  insert into lost_report_private_details(lost_report_id, details)
  values (report_id, coalesce(private_details, ''));
  return report_id;
end;
$$;

