create policy "profiles read own or admin" on profiles for select to authenticated
  using (id = auth.uid() or current_user_is_admin());
create policy "profile update own name" on profiles for update to authenticated
  using (id = auth.uid() and current_user_is_campus_member())
  with check (id = auth.uid());
revoke update on profiles from authenticated;
grant update (full_name) on profiles to authenticated;

create policy "categories read active" on categories for select to authenticated
  using (current_user_is_campus_member() and (active or current_user_is_admin()));
create policy "categories admin insert" on categories for insert to authenticated
  with check (current_user_is_admin());
create policy "categories admin update" on categories for update to authenticated
  using (current_user_is_admin()) with check (current_user_is_admin());

create policy "lost reports campus read" on lost_reports for select to authenticated
  using (
    current_user_is_campus_member()
    and (status = 'open' or owns_lost_report(id) or current_user_is_admin())
  );
create policy "lost reports campus insert" on lost_reports for insert to authenticated
  with check (false);
create policy "lost reports owner or admin update" on lost_reports for update to authenticated
  using (owns_lost_report(id) or current_user_is_admin())
  with check (owns_lost_report(id) or current_user_is_admin());
create policy "lost reports owner or admin delete" on lost_reports for delete to authenticated
  using (false);

create policy "found notices campus read" on found_notices for select to authenticated
  using (
    current_user_is_campus_member()
    and (
      status not in ('disposed', 'withdrawn', 'duplicate')
      or owns_found_notice(id)
      or current_user_is_admin()
    )
  );
create policy "found notices campus insert" on found_notices for insert to authenticated
  with check (false);
create policy "found notices owner or admin update" on found_notices for update to authenticated
  using (owns_found_notice(id) or current_user_is_admin())
  with check (owns_found_notice(id) or current_user_is_admin());
create policy "found notices owner or admin delete" on found_notices for delete to authenticated
  using (false);

create policy "report owners private read" on report_owners for select to authenticated
  using (owner_id = auth.uid() or current_user_is_admin());
create policy "report owners self insert" on report_owners for insert to authenticated
  with check (false);

create policy "lost private owner or admin" on lost_report_private_details for all to authenticated
  using (owns_lost_report(lost_report_id) or current_user_is_admin())
  with check (owns_lost_report(lost_report_id) or current_user_is_admin());
create policy "found private owner or admin" on found_notice_private_details for all to authenticated
  using (owns_found_notice(found_notice_id) or current_user_is_admin())
  with check (owns_found_notice(found_notice_id) or current_user_is_admin());

create policy "possible matches admin read" on possible_matches for select to authenticated
  using (current_user_is_admin());
create policy "possible matches owner insert" on possible_matches for insert to authenticated
  with check (
    current_user_is_campus_member()
    and created_by = auth.uid()
    and (owns_lost_report(lost_report_id) or owns_found_notice(found_notice_id) or current_user_is_admin())
  );
create policy "possible matches admin delete" on possible_matches for delete to authenticated
  using (current_user_is_admin());

create policy "claims claimant or admin read" on claim_attempts for select to authenticated
  using (claimant_id = auth.uid() or current_user_is_admin());
create policy "claims student insert" on claim_attempts for insert to authenticated
  with check (
    current_user_is_campus_member()
    and claimant_id = auth.uid()
    and status = 'pending'
    and exists (
      select 1 from found_notices f
      where f.id = found_notice_id and f.status = 'received'
    )
    and not owns_found_notice(found_notice_id)
    and (lost_report_id is null or owns_lost_report(lost_report_id))
  );
create policy "claims claimant delete own pending" on claim_attempts for delete to authenticated
  using (claimant_id = auth.uid() and status in ('pending', 'needs_info'));

create policy "claim messages claimant or admin read" on claim_messages for select to authenticated
  using (
    current_user_is_admin()
    or exists (
      select 1 from claim_attempts c
      where c.id = claim_id and c.claimant_id = auth.uid()
    )
  );
create policy "claim messages claimant or admin insert" on claim_messages for insert to authenticated
  with check (
    sender_id = auth.uid()
    and (
      current_user_is_admin()
      or exists (
        select 1 from claim_attempts c
        where c.id = claim_id and c.claimant_id = auth.uid() and c.status = 'needs_info'
      )
    )
  );

create policy "audit admin read" on item_audit_log for select to authenticated
  using (current_user_is_admin());

