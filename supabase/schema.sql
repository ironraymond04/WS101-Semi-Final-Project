create extension if not exists pgcrypto;

create type user_role as enum ('student', 'admin');
create type lost_report_status as enum ('open', 'recovered', 'withdrawn', 'closed');
create type found_notice_status as enum (
  'pre_desk', 'received', 'reserved', 'returned', 'disposed', 'withdrawn', 'duplicate'
);
create type claim_status as enum (
  'pending', 'needs_info', 'approved', 'rejected', 'withdrawn',
  'completed', 'reservation_released', 'closed'
);

create table campus_email_domains (
  domain text primary key check (domain = lower(domain) and position('@' in domain) = 0)
);

create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  role user_role not null default 'student',
  created_at timestamptz not null default now()
);

create table categories (
  id integer generated by default as identity primary key,
  name text unique not null check (char_length(name) between 2 and 60),
  active boolean not null default true,
  check (name <> 'Other' or active)
);

create function protect_other_category() returns trigger
language plpgsql as $$
begin
  if old.name = 'Other' and (new.name <> 'Other' or not new.active) then
    raise exception 'The Other category must remain available';
  end if;
  return new;
end;
$$;
create trigger preserve_other_category
  before update on categories for each row execute function protect_other_category();

