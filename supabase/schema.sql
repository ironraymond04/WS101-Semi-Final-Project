create function admin_mark_duplicate_notice(notice_id uuid, canonical_id uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;
  perform 1 from found_notices
  where id = notice_id and status in ('pre_desk', 'received')
  for update;
  if not found then raise exception 'Found notice cannot be marked duplicate'; end if;
  if exists (
    select 1 from claim_attempts
    where found_notice_id = notice_id and status in ('pending', 'needs_info', 'approved')
  ) then raise exception 'Resolve active claims before marking a duplicate'; end if;
  if notice_id = canonical_id or not exists (
    select 1 from found_notices where id = canonical_id and status in ('received', 'reserved', 'returned')
  ) then raise exception 'Canonical custody record is invalid'; end if;
  update found_notices set status = 'duplicate', canonical_found_notice_id = canonical_id, updated_at = now()
  where id = notice_id and status in ('pre_desk', 'received');
  if not found then raise exception 'Found notice cannot be marked duplicate'; end if;
  insert into item_audit_log(action, found_notice_id, details)
  values ('found_notice_marked_duplicate', notice_id, jsonb_build_object('canonical_id', canonical_id));
end;
$$;

create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public, auth as $$
declare
  email_domain text := lower(split_part(new.email, '@', 2));
begin
  if email_domain = '' or not exists (
    select 1 from public.campus_email_domains d where d.domain = email_domain
  ) then
    raise exception 'This email domain is not enabled for campus accounts';
  end if;

  insert into public.profiles(id, email, full_name)
  values (
    new.id,
    lower(new.email),
    coalesce(new.raw_user_meta_data->>'full_name', '')
  );
  return new;
end;
$$;
create trigger on_auth_user_created
  after insert on auth.users for each row execute function handle_new_user();

