create function admin_review_claim(
  claim_id uuid,
  decision claim_status,
  message text default null
) returns void
language plpgsql security definer set search_path = public as $$
declare
  attempt claim_attempts%rowtype;
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;
  if decision not in ('needs_info', 'approved', 'rejected') then
    raise exception 'Invalid claim decision';
  end if;
  if decision = 'needs_info' and coalesce(char_length(trim(message)), 0) = 0 then
    raise exception 'A request for more information is required';
  end if;

  select * into attempt from claim_attempts where id = claim_id for update;
  if not found or attempt.status not in ('pending', 'needs_info') then
    raise exception 'Claim is not awaiting review';
  end if;

  if decision = 'approved' then
    perform 1 from found_notices
    where id = attempt.found_notice_id and status = 'received'
    for update;
    if not found then raise exception 'Found item is not available for reservation'; end if;
  end if;

  update claim_attempts
  set status = decision, updated_at = now()
  where id = claim_id;

  if message is not null and char_length(trim(message)) > 0 then
    insert into claim_messages(claim_id, message) values (claim_id, trim(message));
  end if;

  if decision = 'approved' then
    update found_notices
    set status = 'reserved', updated_at = now()
    where id = attempt.found_notice_id;
  end if;

  insert into item_audit_log(action, found_notice_id, claim_id)
  values ('claim_' || decision::text, attempt.found_notice_id, claim_id);
end;
$$;

create function claimant_respond_to_claim(claim_id uuid, message text) returns void
language plpgsql security definer set search_path = public as $$
declare
  attempt claim_attempts%rowtype;
begin
  select * into attempt from claim_attempts
  where id = claim_id and claimant_id = auth.uid() and status = 'needs_info'
  for update;
  if not found then raise exception 'Claim is not awaiting claimant information'; end if;
  if char_length(trim(message)) not between 1 and 2000 then raise exception 'Invalid response'; end if;

  insert into claim_messages(claim_id, message) values (claim_id, trim(message));
  update claim_attempts set status = 'pending', updated_at = now() where id = claim_id;
end;
$$;

create function claimant_withdraw_claim(claim_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare
  attempt claim_attempts%rowtype;
begin
  select * into attempt from claim_attempts
  where id = claim_id and claimant_id = auth.uid()
    and status in ('pending', 'needs_info', 'approved')
  for update;
  if not found then raise exception 'Claim cannot be withdrawn'; end if;

  if attempt.status = 'approved' then
    update found_notices set status = 'received', updated_at = now()
    where id = attempt.found_notice_id and status = 'reserved';
  end if;

  update claim_attempts set status = 'withdrawn', updated_at = now() where id = claim_id;
  insert into item_audit_log(action, found_notice_id, claim_id)
  values ('claim_withdrawn', attempt.found_notice_id, claim_id);
end;
$$;

create function admin_release_reservation(claim_id uuid, reason text) returns void
language plpgsql security definer set search_path = public as $$
declare
  attempt claim_attempts%rowtype;
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;
  if char_length(trim(reason)) not between 1 and 1000 then raise exception 'A release reason is required'; end if;

  select * into attempt from claim_attempts
  where id = claim_id and status = 'approved'
  for update;
  if not found then raise exception 'Active reservation not found'; end if;

  update found_notices set status = 'received', updated_at = now()
  where id = attempt.found_notice_id and status = 'reserved';
  update claim_attempts set status = 'reservation_released', updated_at = now() where id = claim_id;
  insert into item_audit_log(action, found_notice_id, claim_id, details)
  values ('reservation_released', attempt.found_notice_id, claim_id, jsonb_build_object('reason', trim(reason)));
end;
$$;

create function admin_record_handover(claim_id uuid, notes text default null) returns void
language plpgsql security definer set search_path = public as $$
declare
  attempt claim_attempts%rowtype;
begin
  if not current_user_is_admin() then raise exception 'Admin role required'; end if;

  select * into attempt from claim_attempts
  where id = claim_id and status = 'approved'
  for update;
  if not found then raise exception 'Approved reservation not found'; end if;

  perform 1 from found_notices
  where id = attempt.found_notice_id and status = 'reserved'
  for update;
  if not found then raise exception 'Found item is not reserved'; end if;

  update found_notices
  set status = 'returned', updated_at = now()
  where id = attempt.found_notice_id;
  update claim_attempts set status = 'completed', updated_at = now() where id = claim_id;
  update claim_attempts
  set status = 'closed', updated_at = now()
  where found_notice_id = attempt.found_notice_id and id <> claim_id
    and status in ('pending', 'needs_info');
  if attempt.lost_report_id is not null then
    update lost_reports set status = 'recovered', updated_at = now()
    where id = attempt.lost_report_id and status = 'open';
  end if;

  insert into item_audit_log(action, found_notice_id, claim_id, details)
  values ('handover_recorded', attempt.found_notice_id, claim_id, jsonb_build_object('notes', notes));
end;
$$;

