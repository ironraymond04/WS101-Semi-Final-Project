create function owner_update_lost_report(
  report_id uuid,
  report_title text,
  report_description text,
  report_category_id integer,
  seen_on date,
  seen_location text,
  private_details text
) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not owns_lost_report(report_id) then raise exception 'Report owner required'; end if;
  if not exists (select 1 from categories where id = report_category_id and active) then
    raise exception 'Choose an active category';
  end if;
  update lost_reports
  set title = report_title, description = report_description, category_id = report_category_id,
      last_seen_on = seen_on, last_seen_location = seen_location, updated_at = now()
