create function claimant_create_claim(
  notice_id uuid,
  report_id uuid,
  proof text
) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  created_claim_id uuid;
begin
  if not current_user_is_campus_member() then raise exception 'Verified campus account required'; end if;
  if owns_found_notice(notice_id) then raise exception 'Finders cannot claim their own found notice'; end if;
  perform 1 from found_notices where id = notice_id and status = 'received' for update;
  if not found then raise exception 'Found item is not available for claims'; end if;
  if report_id is not null and (
    not owns_lost_report(report_id)
    or not exists (select 1 from lost_reports where id = report_id and status = 'open')
  ) then
    raise exception 'Link only an open lost report that you own';
  end if;

  insert into claim_attempts(found_notice_id, claimant_id, lost_report_id, evidence)
  values (notice_id, auth.uid(), report_id, proof)
  returning id into created_claim_id;
  return created_claim_id;
end;
$$;

