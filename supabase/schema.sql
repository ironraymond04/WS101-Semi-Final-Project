create policy "campus members read report images" on storage.objects for select to authenticated
  using (bucket_id = 'item-images' and current_user_is_campus_member());
create policy "owners upload report images" on storage.objects for insert to authenticated
  with check (
    bucket_id = 'item-images'
    and current_user_is_campus_member()
    and (storage.foldername(name))[1] = 'users'
    and (storage.foldername(name))[2] = auth.uid()::text
  );
create policy "owners or admins delete report images" on storage.objects for delete to authenticated
  using (
    bucket_id = 'item-images'
    and current_user_is_campus_member()
    and (
      ((storage.foldername(name))[1] = 'users' and (storage.foldername(name))[2] = auth.uid()::text)
      or current_user_is_admin()
    )
  );
